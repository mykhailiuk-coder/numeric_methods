# Лаб. 5, варіант 8, задача 1.1 (формули Ньютона)

x = [2.119, 3.844, 5.569, 7.294, 9.019]
y = [0.605, 0.718, 0.105, 2.157, 3.431]
h = 1.725
n = 4


# таблиця скінченних різниць, d[k][i] - різниця k-го порядку
def table(y):
    d = [y]
    for k in range(1, len(y)):
        row = []
        for i in range(len(d[k - 1]) - 1):
            row.append(d[k - 1][i + 1] - d[k - 1][i])
        d.append(row)
    return d


d = table(y)

print("Таблиця скінченних різниць")
print("i    x       y       dy      d2y     d3y     d4y")
for i in range(5):
    s = str(i) + "  " + "%7.3f %7.3f" % (x[i], y[i])
    for k in range(1, 5):
        if i < len(d[k]):
            s += " %7.3f" % d[k][i]
        else:
            s += "    ---"
    print(s)
print()

# а) x = 3 лежить між x0 і x1, тому формули (2) і (3)
xa = 3
t = (xa - x[0]) / h
dy0 = d[1][0]
d2y0 = d[2][0]
d3y0 = d[3][0]
d4y0 = d[4][0]

p1 = dy0 + d2y0 * (2*t - 1) / 2 + d3y0 * (3*t**2 - 6*t + 2) / 6 \
     + d4y0 * (4*t**3 - 18*t**2 + 22*t - 6) / 24
p1 = p1 / h

p2 = d2y0 + d3y0 * (t - 1) + d4y0 * (6*t**2 - 18*t + 11) / 12
p2 = p2 / h**2

print("1.1 а)")
print("t =", round(t, 4))
print("f'(3) =", round(p1, 3))
print("f''(3) =", round(p2, 3))
print()

# б) x = 9.019 це останній вузол x4, тому формули (8) і (9)
dy3 = d[1][n - 1]
d2y2 = d[2][n - 2]
d3y1 = d[3][n - 3]
d4y0 = d[4][n - 4]

q1 = (dy3 + d2y2 / 2 + d3y1 / 3 + d4y0 / 4) / h
q2 = (d2y2 + d3y1 + 11 * d4y0 / 12) / h**2

print("1.1 б)")
print("f'(9.019) =", round(q1, 3))
print("f''(9.019) =", round(q2, 3))

# --- 1.2 Формула Стірлінга (для центрального вузла x2 = 5.569, t = 0) ---
# Для центрального вузла x2 (i=2):
# Перша різниця береться як середня між упередженою та запізненою: (d[1][1] + d[1][2]) / 2
mu_dy1 = (d[1][1] + d[1][2]) / 2  
# Друга різниця в центрі: d[2][1]
d2y1 = d[2][1]                     
# Четверта різниця в центрі (якщо потрібна для уточнення другої похідної):
d4y0_st = d[4][0] if len(d) > 4 and len(d[4]) > 0 else 0

# Формула Стірлінга для першої та другої похідної при t = 0:
s1 = mu_dy1 / h
s2 = (d2y1 + d4y0_st / 12) / h**2

print("1.2) За формулою Стірлінга (в точці x2 = 5.569):")
print("f'(5.569) =", round(s1, 3))
print("f''(5.569) =", round(s2, 3))
print()


# --- 1.3 Простіші формули для оцінки похідних ---
# У точці x[0] (правобічні різниці):
ds1_0 = (-3*y[0] + 4*y[1] - y[2]) / (2 * h)
ds2_0 = (y[0] - 2*y[1] + y[2]) / h**2

# У центральній точці x[2] (центральні різниці):
ds1_2 = (y[3] - y[1]) / (2 * h)
ds2_2 = (y[3] - 2*y[2] + y[1]) / h**2

# У точці x[4] (лівобічні різниці):
ds1_4 = (y[2] - 4*y[3] + 3*y[4]) / (2 * h)
ds2_4 = (y[2] - 2*y[3] + y[4]) / h**2

print("1.3) За простими формулами (кінцеві та центральні різниці):")
print(f"Вузол x[0] = {x[0]}: f' = {round(ds1_0, 3)}, f'' = {round(ds2_0, 3)}")
print(f"Вузол x[2] = {x[2]}: f' = {round(ds1_2, 3)}, f'' = {round(ds2_2, 3)}")
print(f"Вузол x[4] = {x[4]}: f' = {round(ds1_4, 3)}, f'' = {round(ds2_4, 3)}")
print()


