# таблиця скінченних різниць, d[k][i] - різниця k-го порядку
def table(y):
    d = [y]
    for k in range(1, len(y)):
        row = []
        for i in range(len(d[k - 1]) - 1):
            row.append(d[k - 1][i + 1] - d[k - 1][i])
        d.append(row)
    return d

d = table(y)

print("Таблиця скінченних різниць")
print("i    x       y       dy      d2y     d3y     d4y")
for i in range(5):
    s = str(i) + "  " + "%7.3f %7.3f" % (x[i], y[i])
    for k in range(1, 5):
        if i < len(d[k]):
            s += " %7.3f" % d[k][i]
        else:
            s += "    ---"
    print(s)
print()

