# Лаб. 5, варіант 8, задача 1.1 (формули Ньютона)

x = [2.119, 3.844, 5.569, 7.294, 9.019]
y = [0.605, 0.718, 0.105, 2.157, 3.431]
h = 1.725
n = 4


# таблиця скінченних різниць, d[k][i] - різниця k-го порядку
def table(y):
    d = [y]
    for k in range(1, len(y)):
        row = []
        for i in range(len(d[k - 1]) - 1):
            row.append(d[k - 1][i + 1] - d[k - 1][i])
        d.append(row)
    return d

d = table(y)

print("Таблиця скінченних різниць")
print("i    x       y       dy      d2y     d3y     d4y")
for i in range(5):
    s = str(i) + "  " + "%7.3f %7.3f" % (x[i], y[i])
    for k in range(1, 5):
        if i < len(d[k]):
            s += " %7.3f" % d[k][i]
        else:
            s += "    ---"
    print(s)
print()

# а) x = 3 лежить між x0 і x1, тому формули (2) і (3)
xa = 3
t = (xa - x[0]) / h
dy0 = d[1][0]
d2y0 = d[2][0]
d3y0 = d[3][0]
d4y0 = d[4][0]

p1 = dy0 + d2y0 * (2*t - 1) / 2 + d3y0 * (3*t**2 - 6*t + 2) / 6 \
     + d4y0 * (4*t**3 - 18*t**2 + 22*t - 6) / 24
p1 = p1 / h

p2 = d2y0 + d3y0 * (t - 1) + d4y0 * (6*t**2 - 18*t + 11) / 12
p2 = p2 / h**2

print("1.1 а)")
print("t =", round(t, 4))
print("f'(3) =", round(p1, 3))
print("f''(3) =", round(p2, 3))
print()

# б) x = 9.019 це останній вузол x4, тому формули (8) і (9)
dy3 = d[1][n - 1]
d2y2 = d[2][n - 2]
d3y1 = d[3][n - 3]
d4y0 = d[4][n - 4]

q1 = (dy3 + d2y2 / 2 + d3y1 / 3 + d4y0 / 4) / h
q2 = (d2y2 + d3y1 + 11 * d4y0 / 12) / h**2

print("1.1 б)")
print("f'(9.019) =", round(q1, 3))
print("f''(9.019) =", round(q2, 3))

# 1.2 Формула Стірлінга для точки x = 3 (відносно центрального вузла x2 = 5.569)
# Параметр t для формули Стірлінга рахується від центрального вузла x2:
t_st = (xa - x[2]) / h

# Скінченні різниці для формули Стірлінга:
mu_dy1 = (d[1][1] + d[1][2]) / 2      # Середня перша різниця
d2y1 = d[2][1]                         # Друга різниця в центрі
mu_d3y0 = (d[3][0] + d[3][1]) / 2     # Середня третя різниця
d4y0_st = d[4][0]                      # Четверта різниця

# Перша похідна за многочленом Стірлінга:
s1 = (mu_dy1 + t_st * d2y1 + (3 * t_st**2 - 1) / 6 * mu_d3y0 
      + (4 * t_st**3 - 2 * t_st) / 24 * d4y0_st) / h

# Друга похідна за многочленом Стірлінга:
s2 = (d2y1 + t_st * mu_d3y0 + (6 * t_st**2 - 1) / 12 * d4y0_st) / (h**2)

print("1.2) За формулою Стірлінга (в точці x = 3):")
print("t_st =", round(t_st, 4))
print("f'(3) =", round(s1, 3))
print("f''(3) =", round(s2, 3))
print()


# 1.3 Простіші формули для оцінки похідних у довільній точці x = 3
# Простіші формули базуються на локальній параболічній апроксимації (3 найближчі вузли: x0, x1, x2).
# Похідні від інтерполяційного полінома 2-го степеня в точці x = 3:
# P2'(x) = (2*x - x1 - x2) / ((x0-x1)*(x0-x2)) * y0 + ...
L0_prime = (2 * xa - x[1] - x[2]) / ((x[0] - x[1]) * (x[0] - x[2]))
L1_prime = (2 * xa - x[0] - x[2]) / ((x[1] - x[0]) * (x[1] - x[2]))
L2_prime = (2 * xa - x[0] - x[1]) / ((x[2] - x[0]) * (x[2] - x[1]))
ds1 = L0_prime * y[0] + L1_prime * y[1] + L2_prime * y[2]

# Друга похідна параболи є сталою на всьому відрізку [x0, x2]:
ds2 = (y[0] - 2 * y[1] + y[2]) / (h**2)

print("1.3) За простими різницевими формулами (в точці x = 3):")
print(f"f'(3) = {round(ds1, 3)}")
print(f"f''(3) = {round(ds2, 3)}")
print()


